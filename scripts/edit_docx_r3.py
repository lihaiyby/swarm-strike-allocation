def ensure_rows(table, n_data: int, template_row):
    """把表补到 1 + n_data 行；新增行复制模板行的单元格格式。"""
    want = 1 + n_data
    while len(table.rows) < want:
        new = table.add_row()
        for i, cell in enumerate(new.cells):
            src = template_row.cells[i].paragraphs[0]
            if src.runs:
                run = cell.paragraphs[0].add_run("")
                run.font.size = src.runs[0].font.size
                run.font.name = src.runs[0].font.name
                run.bold = src.runs[0].bold
    while len(table.rows) > want:
        tr = table.rows[-1]._tr
        tr.getparent().remove(tr)


